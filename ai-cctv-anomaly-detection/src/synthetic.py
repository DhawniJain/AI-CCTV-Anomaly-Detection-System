"""SYNTHETIC test fixture - for SOFTWARE TESTING ONLY.

Generates a handful of tiny artificial videos (a grey scene with a small moving square = "normal";
the same scene plus a large flickering blob = "abnormal"). It exists so the pipeline, tests and
smoke-test can run without downloading anything. Results obtained from it are meaningless for
your project and MUST NEVER be reported as dataset results.
"""
from __future__ import annotations

from pathlib import Path

import cv2
import numpy as np

MARKER = "SYNTHETIC_FIXTURE.txt"


def _write_video(path: Path, abnormal: bool, seed: int, n_frames: int = 50, w: int = 160, h: int = 120, fps: int = 10):
    rng = np.random.default_rng(seed)
    writer = cv2.VideoWriter(str(path), cv2.VideoWriter_fourcc(*"mp4v"), fps, (w, h))
    if not writer.isOpened():
        raise RuntimeError("OpenCV could not open a VideoWriter (mp4v) to create the synthetic fixture.")
    x0, speed = int(rng.integers(10, 40)), int(rng.integers(2, 4))
    for i in range(n_frames):
        frame = np.full((h, w, 3), 90, np.uint8)
        frame[:, :, 1] += 15
        x = (x0 + speed * i) % (w - 20)
        cv2.rectangle(frame, (x, 60), (x + 14, 90), (200, 180, 60), -1)  # the "person"
        if abnormal:
            if i % 2 == 0:
                cv2.circle(frame, (int(rng.integers(30, w - 30)), int(rng.integers(25, h - 25))), 22, (30, 30, 240), -1)
        noise = rng.integers(-4, 5, frame.shape, dtype=np.int16)
        writer.write(np.clip(frame.astype(np.int16) + noise, 0, 255).astype(np.uint8))
    writer.release()


def make_synthetic_dataset(root: Path, n_normal: int = 6, n_abnormal: int = 4) -> Path:
    root = Path(root)
    if (root / MARKER).exists():
        return root
    (root / "normal").mkdir(parents=True, exist_ok=True)
    (root / "abnormal").mkdir(parents=True, exist_ok=True)
    for i in range(n_normal):
        _write_video(root / "normal" / f"synthetic_normal_{i}.mp4", False, seed=i)
    for i in range(n_abnormal):
        _write_video(root / "abnormal" / f"synthetic_abnormal_{i}.mp4", True, seed=100 + i)
    (root / MARKER).write_text("SYNTHETIC data generated by src/synthetic.py for software testing only.\n")
    return root
